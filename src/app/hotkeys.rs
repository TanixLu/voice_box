//! Passive global shortcuts run on a message thread; simulated keys use RAII.
use std::{cell::RefCell, mem::size_of, sync::mpsc, thread::JoinHandle};
use windows::{
    Win32::{
        Foundation::{LPARAM, LRESULT, WAIT_FAILED, WPARAM},
        System::LibraryLoader::GetModuleHandleW,
        UI::{
            Input::KeyboardAndMouse::*,
            WindowsAndMessaging::{
                CallNextHookEx, DispatchMessageW, HC_ACTION, HHOOK, KBDLLHOOKSTRUCT,
                LLKHF_EXTENDED, LLKHF_INJECTED, MSG, MWMO_INPUTAVAILABLE,
                MsgWaitForMultipleObjectsEx, PM_REMOVE, PeekMessageW, QS_ALLINPUT,
                SetWindowsHookExW, UnhookWindowsHookEx, WH_KEYBOARD_LL, WM_KEYDOWN, WM_KEYUP,
                WM_SYSKEYDOWN, WM_SYSKEYUP,
            },
        },
    },
    core::PCWSTR,
};

const SIMULATED_INPUT_TAG: usize = 0x5642_4b59;

#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub(super) struct Hotkey {
    pub key: u16,
    pub modifiers: u32,
}

impl Hotkey {
    pub fn valid(self) -> bool {
        self.valid_for_hold() && !is_modifier(self.key)
    }
    pub fn valid_for_hold(self) -> bool {
        key_name(self.key).is_some() && self.modifiers & !0xf == 0
    }
    pub fn label(self) -> String {
        let mut parts = Vec::new();
        for (flag, name) in [(2, "Ctrl"), (4, "Shift"), (1, "Alt"), (8, "Win")] {
            if self.modifiers & flag != 0 {
                parts.push(name.to_owned());
            }
        }
        parts.push(key_name(self.key).unwrap_or_else(|| "无效按键".into()));
        parts.join(" + ")
    }
    pub fn pressed() -> Option<Self> {
        let modifiers = [(0x11, 2), (0x10, 4), (0x12, 1), (0x5b, 8), (0x5c, 8)]
            .into_iter()
            .filter(|&(key, _)| down(key))
            .fold(0, |flags, (_, flag)| flags | flag);
        (8..=0xfe)
            .find(|&key| !is_modifier(key) && key_name(key).is_some() && down(key))
            .map(|key| Self { key, modifiers })
    }
    pub fn pressed_modifier() -> Option<Self> {
        [0xa0, 0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0x5b, 0x5c]
            .into_iter()
            .find(|&key| down(key))
            .map(|key| Self { key, modifiers: 0 })
    }
}

fn is_modifier(key: u16) -> bool {
    matches!(key, 0x10..=0x12 | 0x5b..=0x5c | 0xa0..=0xa5)
}

fn key_name(key: u16) -> Option<String> {
    Some(match key {
        0x30..=0x39 | 0x41..=0x5a => char::from_u32(u32::from(key))?.to_string(),
        0x70..=0x87 => format!("F{}", key - 0x6f),
        0x60..=0x69 => format!("Num {}", key - 0x60),
        0x08 => "Backspace".into(),
        0x09 => "Tab".into(),
        0x0d => "Enter".into(),
        0x1b => "Esc".into(),
        0x20 => "Space".into(),
        0x10 => "Shift".into(),
        0x11 => "Ctrl".into(),
        0x12 => "Alt".into(),
        0x5b => "Left Win".into(),
        0x5c => "Right Win".into(),
        0xa0 => "Left Shift".into(),
        0xa1 => "Right Shift".into(),
        0xa2 => "Left Ctrl".into(),
        0xa3 => "Right Ctrl".into(),
        0xa4 => "Left Alt".into(),
        0xa5 => "Right Alt".into(),
        0x21 => "PageUp".into(),
        0x22 => "PageDown".into(),
        0x23 => "End".into(),
        0x24 => "Home".into(),
        0x25 => "Left".into(),
        0x26 => "Up".into(),
        0x27 => "Right".into(),
        0x28 => "Down".into(),
        0x2d => "Insert".into(),
        0x2e => "Delete".into(),
        0x6a => "Num *".into(),
        0x6b => "Num +".into(),
        0x6d => "Num -".into(),
        0x6e => "Num .".into(),
        0x6f => "Num /".into(),
        0xba => ";".into(),
        0xbb => "=".into(),
        0xbc => ",".into(),
        0xbd => "-".into(),
        0xbe => ".".into(),
        0xbf => "/".into(),
        0xc0 => "`".into(),
        0xdb => "[".into(),
        0xdc => "\\".into(),
        0xdd => "]".into(),
        0xde => "'".into(),
        _ => return None,
    })
}

fn down(key: u16) -> bool {
    unsafe { GetAsyncKeyState(i32::from(key)) < 0 }
}

struct KeyEvent {
    key: u32,
    scan: u32,
    extended: bool,
    pressed: bool,
}

thread_local! {
    static KEY_EVENTS: RefCell<Option<mpsc::Sender<KeyEvent>>> = const { RefCell::new(None) };
}

unsafe extern "system" fn keyboard_hook(code: i32, wparam: WPARAM, lparam: LPARAM) -> LRESULT {
    if code == HC_ACTION as i32
        && lparam.0 != 0
        && matches!(
            wparam.0 as u32,
            WM_KEYDOWN | WM_KEYUP | WM_SYSKEYDOWN | WM_SYSKEYUP
        )
    {
        let input = unsafe { &*(lparam.0 as *const KBDLLHOOKSTRUCT) };
        // Ignore our automatic push-to-talk events to avoid recursive playback.
        // Keep supporting shortcuts generated by other keyboard software.
        if input.flags & LLKHF_INJECTED == Default::default()
            || input.dwExtraInfo != SIMULATED_INPUT_TAG
        {
            let _ = KEY_EVENTS.try_with(|events| {
                if let Ok(events) = events.try_borrow()
                    && let Some(events) = events.as_ref()
                {
                    // Keep the hook short: matching and repainting happen after
                    // returning to the message loop, outside the hook callback.
                    let _ = events.send(KeyEvent {
                        key: input.vkCode,
                        scan: input.scanCode,
                        extended: input.flags & LLKHF_EXTENDED != Default::default(),
                        pressed: matches!(wparam.0 as u32, WM_KEYDOWN | WM_SYSKEYDOWN),
                    });
                }
            });
        }
    }
    // Never consume keyboard input, including matching shortcuts and injected
    // events: other applications must receive the same keys normally.
    unsafe { CallNextHookEx(None, code, wparam, lparam) }
}

struct KeyboardHook(HHOOK);
impl KeyboardHook {
    fn install(events: mpsc::Sender<KeyEvent>) -> windows::core::Result<Self> {
        let module = unsafe { GetModuleHandleW(PCWSTR::null())? };
        let handle = unsafe {
            SetWindowsHookExW(WH_KEYBOARD_LL, Some(keyboard_hook), Some(module.into()), 0)?
        };
        KEY_EVENTS.with(|sender| sender.replace(Some(events)));
        Ok(Self(handle))
    }
}
impl Drop for KeyboardHook {
    fn drop(&mut self) {
        let _ = unsafe { UnhookWindowsHookEx(self.0) };
        KEY_EVENTS.with(|sender| sender.replace(None));
    }
}

struct KeyState([bool; 256]);
impl KeyState {
    fn new() -> Self {
        // A key already held when the listener starts must be released before
        // it can trigger a shortcut. Keep left/right modifiers independent.
        Self(std::array::from_fn(|key| down(key as u16)))
    }

    fn update(&mut self, event: KeyEvent) -> Option<Hotkey> {
        let key = match event.key {
            0x10 => unsafe { MapVirtualKeyW(event.scan, MAPVK_VSC_TO_VK_EX) },
            0x11 => {
                if event.extended {
                    0xa3
                } else {
                    0xa2
                }
            }
            0x12 => {
                if event.extended {
                    0xa5
                } else {
                    0xa4
                }
            }
            key => key,
        };
        let pressed = self.0.get_mut(key as usize)?;
        let was_pressed = std::mem::replace(pressed, event.pressed);
        if !event.pressed || was_pressed || is_modifier(key as u16) {
            return None;
        }
        let mut modifiers = 0;
        for (left, right, flag) in [
            (0xa2, 0xa3, 2),
            (0xa0, 0xa1, 4),
            (0xa4, 0xa5, 1),
            (0x5b, 0x5c, 8),
        ] {
            if self.0[left] || self.0[right] {
                modifiers |= flag;
            }
        }
        Some(Hotkey {
            key: key as u16,
            modifiers,
        })
    }
}

pub(super) enum Event {
    Trigger { index: usize, revision: u64 },
    Error(String),
}
pub(super) struct Hotkeys {
    sender: mpsc::Sender<(u64, Vec<Option<Hotkey>>)>,
    pub receiver: mpsc::Receiver<Event>,
    thread: Option<JoinHandle<()>>,
}
impl Hotkeys {
    pub fn new(ctx: &egui::Context) -> anyhow::Result<Self> {
        let (sender, commands) = mpsc::channel::<(u64, Vec<Option<Hotkey>>)>();
        let (events, receiver) = mpsc::channel();
        let ctx = ctx.clone();
        let thread = std::thread::Builder::new()
            .name("VoiceBoxHotkeys".into())
            .spawn(move || {
                let (key_events, keys) = mpsc::channel();
                let _hook = match KeyboardHook::install(key_events) {
                    Ok(hook) => hook,
                    Err(error) => {
                        let _ = events.send(Event::Error(format!("无法监听全局快捷键：{error}")));
                        ctx.request_repaint();
                        return;
                    }
                };
                let mut state = KeyState::new();
                let mut bindings: Vec<Option<Hotkey>> = Vec::new();
                let mut revision = 0;
                loop {
                    let mut msg = MSG::default();
                    while unsafe { PeekMessageW(&mut msg, None, 0, 0, PM_REMOVE).as_bool() } {
                        unsafe {
                            DispatchMessageW(&msg);
                        }
                    }
                    let mut repaint = false;
                    for event in keys.try_iter() {
                        if let Some(key) = state.update(event)
                            && let Some(index) =
                                bindings.iter().position(|binding| *binding == Some(key))
                        {
                            let _ = events.send(Event::Trigger { index, revision });
                            repaint = true;
                        }
                    }
                    if repaint {
                        ctx.request_repaint();
                    }
                    // Process input against its current revision first. Changing
                    // bindings never treats a held key as a fresh key press.
                    match commands.try_recv() {
                        Ok((mut next_revision, mut next_bindings)) => {
                            for next in commands.try_iter() {
                                (next_revision, next_bindings) = next;
                            }
                            revision = next_revision;
                            bindings = next_bindings
                                .into_iter()
                                .map(|key| key.filter(|key| key.valid()))
                                .collect();
                        }
                        Err(mpsc::TryRecvError::Disconnected) => break,
                        Err(mpsc::TryRecvError::Empty) => {}
                    }
                    // Wake immediately for keyboard messages; the timeout only
                    // bounds how long configuration/shutdown commands can wait.
                    let result = unsafe {
                        MsgWaitForMultipleObjectsEx(None, 10, QS_ALLINPUT, MWMO_INPUTAVAILABLE)
                    };
                    if result == WAIT_FAILED {
                        let error = windows::core::Error::from_thread();
                        let _ = events.send(Event::Error(format!("等待全局键盘事件失败：{error}")));
                        ctx.request_repaint();
                        break;
                    }
                }
            })?;
        Ok(Self {
            sender,
            receiver,
            thread: Some(thread),
        })
    }
    pub fn configure(&self, revision: u64, bindings: Vec<Option<Hotkey>>) {
        let _ = self.sender.send((revision, bindings));
    }
}
impl Drop for Hotkeys {
    fn drop(&mut self) {
        // Disconnect before joining the message thread.
        let (replacement, _) = mpsc::channel();
        self.sender = replacement;
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

#[derive(Default)]
pub(super) struct HeldKeys(Vec<u16>);
impl HeldKeys {
    pub fn press(key: Hotkey) -> anyhow::Result<Self> {
        anyhow::ensure!(key.valid_for_hold(), "自动按键无效");
        let mut held = Self::default();
        let mut keys = Vec::new();
        for (flag, vk) in [(2, 0x11), (4, 0x10), (1, 0x12), (8, 0x5b)] {
            if key.modifiers & flag != 0 {
                keys.push(vk);
            }
        }
        keys.push(key.key);
        for vk in keys {
            // Never release a key the user was already holding themselves.
            if !down(vk) {
                anyhow::ensure!(
                    send_key(vk, false),
                    "无法自动按住 {}，请检查游戏与 VoiceBox 的权限",
                    key.label()
                );
                held.0.push(vk);
            }
        }
        Ok(held)
    }
}
fn send_key(key: u16, release: bool) -> bool {
    let scan = unsafe { MapVirtualKeyW(u32::from(key), MAPVK_VK_TO_VSC_EX) };
    let mut flags = if release {
        KEYEVENTF_KEYUP
    } else {
        KEYBD_EVENT_FLAGS(0)
    };
    if scan != 0 {
        flags |= KEYEVENTF_SCANCODE;
    }
    if scan & 0xff00 == 0xe000 {
        flags |= KEYEVENTF_EXTENDEDKEY;
    }
    let input = INPUT {
        r#type: INPUT_KEYBOARD,
        Anonymous: INPUT_0 {
            ki: KEYBDINPUT {
                wVk: if scan == 0 {
                    VIRTUAL_KEY(key)
                } else {
                    VIRTUAL_KEY(0)
                },
                wScan: (scan & 0xff) as u16,
                dwFlags: flags,
                dwExtraInfo: SIMULATED_INPUT_TAG,
                ..Default::default()
            },
        },
    };
    unsafe { SendInput(&[input], size_of::<INPUT>() as i32) == 1 }
}
impl Drop for HeldKeys {
    fn drop(&mut self) {
        for key in self.0.drain(..).rev() {
            send_key(key, true);
        }
    }
}
